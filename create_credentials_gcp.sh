# --- Create / update custom IAM role -----------------------------------
echo "Configuring IAM role: $role_name"
permissions_csv="$(concat_permissions "${permissions[@]}")"

role_id=$(gcloud iam roles describe "$role_name" \
    --project="$project_name" --format="value(name)" \
    --verbosity=none --quiet 2>/dev/null || true)

if [ -z "$role_id" ]; then
    echo "  Creating role $role_name ..."
    gcloud iam roles create "$role_name" \
        --description="PipeOps role — provisioning and cluster management" \
        --permissions="$permissions_csv" \
        --project="$project_name" --quiet
    role_id=$(gcloud iam roles describe "$role_name" \
        --project="$project_name" --format="value(name)" \
        --verbosity=none --quiet)
else
    echo "  Updating existing role $role_name ..."
    gcloud iam roles update "$role_name" \
        --permissions="$permissions_csv" \
        --project="$project_name" --quiet
fi
echo "  Role ready: $role_id"

# --- Create service account --------------------------------------------
service_account_email="${service_account_name}@${project_name}.iam.gserviceaccount.com"

echo "Configuring service account: $service_account_name"
if gcloud iam service-accounts describe "$service_account_email" \
    --project="$project_name" --verbosity=none &>/dev/null; then
    echo "  Service account already exists, skipping creation."
else
    echo "  Creating service account ..."
    gcloud iam service-accounts create "$service_account_name" \
        --display-name="$service_account_name" \
        --project="$project_name" --quiet
fi

# --- Bind role to service account --------------------------------------
echo "Binding role to service account ..."
gcloud projects add-iam-policy-binding "$project_name" \
    --member="serviceAccount:$service_account_email" \
    --role="$role_id" \
    --condition=None \
    --quiet >/dev/null
echo "  Role binding applied."

# --- Generate key ------------------------------------------------------
key_file="key.json"
echo "Generating service account key ..."
gcloud iam service-accounts keys create "$key_file" \
    --iam-account="$service_account_email" --quiet

