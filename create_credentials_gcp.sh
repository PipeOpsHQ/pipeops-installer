#!/bin/bash
#
# PipeOps GCP Credentials Setup Script
# Creates a service account with the permissions required to provision
# and manage GKE clusters, networking, storage, and artifact registry.
#
# Usage:
#   ./create_credentials_gcp.sh <project_id> <role_name> <service_account_name>
#
# Example:
#   ./create_credentials_gcp.sh my-gcp-project pipeops-role pipeops-sa
#
# Prerequisites:
#   - gcloud CLI installed and authenticated (gcloud auth login)
#   - Owner or IAM Admin role on the target project
#   - jq installed

set -euo pipefail

# --- Argument validation -----------------------------------------------
if [ "$#" -lt 3 ]; then
    echo "Usage: $0 <project_id> <role_name> <service_account_name>"
    echo "  <project_id>:            GCP project to create resources in"
    echo "  <role_name>:             Custom IAM role name for PipeOps"
    echo "  <service_account_name>:  Service account name for PipeOps"
    exit 1
fi

project_name="$1"
role_name="$2"
service_account_name="$3"

# --- Pre-flight checks -------------------------------------------------
for cmd in gcloud jq; do
    if ! command -v "$cmd" &>/dev/null; then
        echo "Error: '$cmd' is required but not installed." >&2
        exit 1
    fi
done

if ! gcloud auth list --filter=status:ACTIVE --format="value(account)" 2>/dev/null | grep -q .; then
    echo "Error: No active gcloud authentication. Run 'gcloud auth login' first." >&2
    exit 1
fi

# --- Enable required APIs ---------------------------------------------
echo "Activating required GCP APIs..."
apis=(
    container.googleapis.com
    compute.googleapis.com
    artifactregistry.googleapis.com
    storage.googleapis.com
    cloudresourcemanager.googleapis.com
    run.googleapis.com
)
for api in "${apis[@]}"; do
    if ! gcloud services enable "$api" --project="$project_name" --quiet 2>/dev/null; then
        echo "Warning: Failed to enable $api — you may need to enable it manually." >&2
    fi
done
echo "APIs activated."

